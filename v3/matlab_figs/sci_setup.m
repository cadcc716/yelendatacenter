    'defaultAxesTickDir', 'in', 'defaultAxesBox', 'on', 'defaultFigureColor', 'w', ...
    'defaultAxesLabelFontSizeMultiplier', 10/9, 'defaultAxesTitleFontSizeMultiplier', 1, ...
    'defaultTextInterpreter', 'tex', 'defaultLegendInterpreter', 'tex', 'defaultAxesTickLabelInterpreter', 'tex');
end
